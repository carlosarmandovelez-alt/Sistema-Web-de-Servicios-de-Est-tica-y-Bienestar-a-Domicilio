-- -----------------------------------------------------
-- Funcion para actualizar fecha_actualizacion
-- (reemplaza ON UPDATE CURRENT_TIMESTAMP de MySQL)
-- -----------------------------------------------------
create or replace function public.set_fecha_actualizacion()
returns trigger
language plpgsql
as $$
begin
    new.fecha_actualizacion = now();
    return new;
end;
$$;

-- -----------------------------------------------------
-- categoria
-- -----------------------------------------------------
create table if not exists public.categoria (
    id_categoria integer generated by default as identity primary key,
    nombre varchar(100) not null
);

create unique index if not exists uq_categoria_nombre on public.categoria (nombre);

-- -----------------------------------------------------
-- usuario
-- -----------------------------------------------------
create table if not exists public.usuario (
    id_usuario integer generated by default as identity primary key,
    email varchar(150) not null,
    password_hash varchar(255) not null,
    rol varchar(20) not null check (rol in ('cliente', 'proveedor')),
    nombre varchar(100) not null,
    apellido varchar(100) not null,
    telefono varchar(20),
    estado_cuenta varchar(20) not null default 'activo' check (estado_cuenta in ('activo', 'inactivo')),
    fecha_registro timestamp not null default current_timestamp,
    fecha_actualizacion timestamp not null default current_timestamp
);

create unique index if not exists uq_usuario_email on public.usuario (email);

create or replace trigger trg_usuario_fecha_actualizacion
    before update on public.usuario
    for each row execute function public.set_fecha_actualizacion();

-- -----------------------------------------------------
-- cliente
-- -----------------------------------------------------
create table if not exists public.cliente (
    id_cliente integer primary key references public.usuario (id_usuario)
);

create index if not exists fk_cliente_usuario1_idx on public.cliente (id_cliente);

-- -----------------------------------------------------
-- direccion
-- -----------------------------------------------------
create table if not exists public.direccion (
    id_direccion integer generated by default as identity primary key,
    es_principal boolean not null default false,
    telefono varchar(255) not null,
    ciudad varchar(100) not null,
    barrio_sector varchar(150),
    informacion_complementaria varchar(255),
    fecha_creacion timestamp not null default current_timestamp,
    cliente_id_cliente integer not null references public.cliente (id_cliente)
);

create index if not exists fk_direccion_cliente1_idx on public.direccion (cliente_id_cliente);

-- -----------------------------------------------------
-- proveedor
-- -----------------------------------------------------
create table if not exists public.proveedor (
    perfil_profesional text,
    id_proveedor integer primary key references public.usuario (id_usuario)
);

create index if not exists fk_proveedor_usuario1_idx on public.proveedor (id_proveedor);

-- -----------------------------------------------------
-- disponibilidad
-- -----------------------------------------------------
create table if not exists public.disponibilidad (
    id_disponibilidad integer generated by default as identity primary key,
    dia_semana varchar(10) not null check (dia_semana in ('lunes', 'martes', 'miercoles', 'jueves', 'viernes', 'sabado', 'domingo')),
    hora_inicio time not null,
    hora_fin time not null,
    id_proveedor integer not null references public.proveedor (id_proveedor)
);

create index if not exists fk_disponibilidad_proveedor1_idx on public.disponibilidad (id_proveedor);

-- -----------------------------------------------------
-- recuperacion_password
-- -----------------------------------------------------
create table if not exists public.recuperacion_password (
    id_recuperacion integer generated by default as identity primary key,
    id_usuario integer not null references public.usuario (id_usuario) on delete cascade on update cascade,
    codigo_token varchar(255) not null,
    fecha_expiracion timestamp not null,
    usado boolean not null default false,
    fecha_creacion timestamp not null default current_timestamp
);

create index if not exists idx_recuperacion_usuario on public.recuperacion_password (id_usuario);

-- -----------------------------------------------------
-- servicio
-- -----------------------------------------------------
create table if not exists public.servicio (
    id_servicio integer generated by default as identity primary key,
    id_categoria integer not null references public.categoria (id_categoria) on delete restrict on update cascade,
    nombre varchar(150) not null,
    descripcion text,
    duracion_minutos integer not null,
    precio numeric(10,2) not null,
    estado varchar(20) not null default 'activo' check (estado in ('activo', 'inactivo')),
    fecha_creacion timestamp not null default current_timestamp,
    fecha_actualizacion timestamp not null default current_timestamp,
    id_proveedor integer not null references public.proveedor (id_proveedor)
);

create index if not exists idx_servicio_categoria on public.servicio (id_categoria);
create index if not exists fk_servicio_proveedor1_idx on public.servicio (id_proveedor);

create or replace trigger trg_servicio_fecha_actualizacion
    before update on public.servicio
    for each row execute function public.set_fecha_actualizacion();

-- -----------------------------------------------------
-- servicio_insumo
-- -----------------------------------------------------
create table if not exists public.servicio_insumo (
    id_insumo integer generated by default as identity primary key,
    id_servicio integer not null references public.servicio (id_servicio) on delete cascade on update cascade,
    nombre varchar(150) not null,
    tipo varchar(20) not null default 'insumo' check (tipo in ('insumo', 'equipo'))
);

create index if not exists idx_insumo_servicio on public.servicio_insumo (id_servicio);

-- -----------------------------------------------------
-- servicio_multimedia
-- -----------------------------------------------------
create table if not exists public.servicio_multimedia (
    id_multimedia integer generated by default as identity primary key,
    id_servicio integer not null references public.servicio (id_servicio) on delete cascade on update cascade,
    tipo_archivo varchar(10) not null check (tipo_archivo in ('foto', 'video')),
    url_archivo varchar(500) not null,
    orden smallint not null default 0
);

create index if not exists idx_multimedia_servicio on public.servicio_multimedia (id_servicio);

-- -----------------------------------------------------
-- solicitud_reserva
-- -----------------------------------------------------
create table if not exists public.solicitud_reserva (
    id_solicitud integer generated by default as identity primary key,
    id_servicio integer not null references public.servicio (id_servicio) on delete restrict on update cascade,
    nombre_servicio_snapshot varchar(150) not null,
    precio_snapshot numeric(10,2) not null,
    duracion_snapshot_minutos smallint not null,
    fecha_hora_solicitada timestamp not null,
    fecha_hora_propuesta timestamp,
    direccion_texto varchar(255) not null,
    barrio_sector varchar(150),
    informacion_complementaria varchar(255),
    observaciones text,
    estado varchar(20) not null default 'pendiente' check (estado in ('pendiente', 'sugerida', 'aceptada', 'completada', 'cancelada', 'rechazada')),
    motivo_rechazo_cancelacion varchar(255),
    fecha_creacion timestamp not null default current_timestamp,
    fecha_actualizacion timestamp not null default current_timestamp,
    id_cliente integer not null references public.cliente (id_cliente),
    id_proveedor integer not null references public.proveedor (id_proveedor)
);

create index if not exists idx_solicitud_servicio on public.solicitud_reserva (id_servicio);
create index if not exists fk_solicitud_reserva_cliente1_idx on public.solicitud_reserva (id_cliente);
create index if not exists fk_solicitud_reserva_proveedor1_idx on public.solicitud_reserva (id_proveedor);

create or replace trigger trg_solicitud_fecha_actualizacion
    before update on public.solicitud_reserva
    for each row execute function public.set_fecha_actualizacion();

-- -----------------------------------------------------
-- zona_cobertura
-- -----------------------------------------------------
create table if not exists public.zona_cobertura (
    id_zona integer generated by default as identity primary key,
    ciudad varchar(100) not null,
    barrio_sector varchar(150),
    id_proveedor integer not null references public.proveedor (id_proveedor)
);

create index if not exists fk_zona_cobertura_proveedor1_idx on public.zona_cobertura (id_proveedor);

-- -----------------------------------------------------
-- token_invalido
-- -----------------------------------------------------
create table if not exists public.token_invalido (
    id_token integer generated by default as identity primary key,
    token varchar(500) not null,
    fecha_invalidacion timestamp not null default current_timestamp
);

-- -----------------------------------------------------
-- periodo_no_disponible
-- -----------------------------------------------------
create table if not exists public.periodo_no_disponible (
    id_periodo integer generated by default as identity primary key,
    id_proveedor integer not null references public.proveedor (id_proveedor) on delete cascade,
    fecha_inicio date not null,
    fecha_fin date not null,
    motivo varchar(255)
);

create index if not exists idx_periodo_no_disponible_proveedor on public.periodo_no_disponible (id_proveedor);
